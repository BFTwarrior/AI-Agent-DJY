import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const LOCALES = ['zh-CN', 'en-US', 'ja-JP', 'ko-KR'];
const DEFAULT_LOCALE = 'en-US';
const HTML_START = '<!-- BEGIN GENERATED I18N (scripts/build-i18n.mjs) -->';
const HTML_END = '<!-- END GENERATED I18N -->';
const JS_START = '/* BEGIN GENERATED I18N (scripts/build-i18n.mjs) */';
const JS_END = '/* END GENERATED I18N */';

const RUNTIME = `/* Generated by scripts/build-i18n.mjs. Do not edit by hand. */
(function (global) {
  'use strict';
  var DATA = __I18N_DATA__;
  var LOCALES = __I18N_LOCALES__;
  var DEFAULT_LOCALE = __I18N_DEFAULT__;

  function normalizeLocale(value) {
    var raw = String(value == null ? '' : value).trim().split('@')[0].split('.')[0].replace(/_/g, '-').toLowerCase();
    if (!raw) return '';
    // Mirrors normalizeLocale in src/i18n.mjs: a whitelist, not a prefix
    // match. zh-TW/zh-HK/zh-Hant stay unsupported so Traditional readers are
    // not silently served Simplified text; zh-Hans and zh-Hans-<region> are
    // Simplified and map to zh-CN.
    var region = raw.split('-');
    if (raw === 'zh' || raw === 'zh-cn' || raw === 'zh-hans' || (region[0] === 'zh' && region[1] === 'hans' && region.length === 3 && region[2].length === 2)) return 'zh-CN';
    if (raw === 'ja' || raw === 'ja-jp') return 'ja-JP';
    if (raw === 'ko' || raw === 'ko-kr') return 'ko-KR';
    if (raw === 'en' || (region[0] === 'en' && region.length === 2 && region[1].length === 2)) return 'en-US';
    return '';
  }

  var LOCALE_STORAGE_KEY = 'agent-teams-locale-v1';

  function localConfig() {
    try {
      var boot = global.__AGENT_TEAMS_UI__;
      return boot && boot.console && boot.console.localization ? boot.console.localization : null;
    } catch (error) {
      return null;
    }
  }

  function storedLocale() {
    try {
      var storage = global.localStorage;
      if (!storage) return '';
      return normalizeLocale(storage.getItem(LOCALE_STORAGE_KEY));
    } catch (error) {
      return '';
    }
  }

  function previewLocale() {
    var search = '';
    try {
      search = String(global.location && global.location.search || '');
    } catch (error) {
      return '';
    }
    var match = /[?&]lang=([^&#]*)/.exec(search);
    if (!match) return '';
    var raw = match[1];
    try {
      raw = decodeURIComponent(raw.replace(/\\+/g, ' '));
    } catch (error) {
      return '';
    }
    return normalizeLocale(raw);
  }

  function htmlLocale() {
    try {
      var doc = global.document;
      var tag = doc && doc.documentElement;
      return normalizeLocale(tag && tag.getAttribute ? tag.getAttribute('lang') : '');
    } catch (error) {
      return '';
    }
  }

  function navigatorLocale() {
    try {
      var nav = global.navigator;
      if (!nav) return '';
      return normalizeLocale(nav.language || (nav.languages && nav.languages[0]) || '');
    } catch (error) {
      return '';
    }
  }

  function resolveLocale() {
    var preview = previewLocale();
    if (preview) return preview;
    var stored = storedLocale();
    if (stored) return stored;
    var configured = normalizeLocale(localConfig() && localConfig().locale);
    if (configured) return configured;
    var html = htmlLocale();
    if (html) return html;
    var navigatorValue = navigatorLocale();
    if (navigatorValue) return navigatorValue;
    return DEFAULT_LOCALE;
  }

  function validTimeZone(value) {
    if (!value) return false;
    try {
      new Intl.DateTimeFormat('en-US', { timeZone: String(value) }).format(new Date(0));
      return true;
    } catch (error) {
      return false;
    }
  }

  function resolveTimeZone() {
    var configured = localConfig();
    if (configured && validTimeZone(configured.timeZone)) return String(configured.timeZone);
    try {
      var detected = Intl.DateTimeFormat().resolvedOptions().timeZone;
      if (validTimeZone(detected)) return detected;
    } catch (error) { /* Intl is optional in constrained hosts */ }
    return 'UTC';
  }

  function interpolate(text, values) {
    if (values == null) return String(text);
    var list = Array.isArray(values) ? values : [values];
    return String(text).replace(/\\{(\\d+)\\}/g, function (token, index) {
      var position = Number(index);
      return position < list.length ? String(list[position]) : token;
    });
  }

  var locale = resolveLocale();
  var timeZone = resolveTimeZone();
  var compiled = Object.create(null);

  function dictFor(name) {
    return DATA[name] || DATA[DEFAULT_LOCALE];
  }

  function compileFor(name) {
    if (compiled[name]) return compiled[name];
    var dict = dictFor(name);
    var strings = dict.strings || {};
    var patterns = dict.patterns || [];
    var patternMap = Object.create(null);
    var matchers = [];
    var ordered = patterns.slice().sort(function (left, right) {
      return String(right.source).length - String(left.source).length;
    });
    for (var index = 0; index < ordered.length; index += 1) {
      patternMap[ordered[index].source] = ordered[index].target;
      matchers.push(compilePattern(ordered[index]));
    }
    compiled[name] = { strings: strings, patternMap: patternMap, matchers: matchers };
    return compiled[name];
  }

  function escapeRegExp(value) {
    return String(value).replace(/[.*+?^\${}()|[\\]\\\\]/g, '\\\\$&');
  }

  function compilePattern(pattern) {
    var source = String(pattern.source);
    var parts = [];
    var lastIndex = 0;
    var matcher = /\\{(\\d+)\\}/g;
    var match;
    while ((match = matcher.exec(source))) {
      parts.push({ literal: source.slice(lastIndex, match.index) });
      parts.push({ index: Number(match[1]) });
      lastIndex = match.index + match[0].length;
    }
    parts.push({ literal: source.slice(lastIndex) });
    var body = '';
    var placeholders = parts.filter(function (part) { return part.index !== undefined; });
    var placeholderNumber = 0;
    for (var index = 0; index < parts.length; index += 1) {
      var part = parts[index];
      if (part.literal !== undefined) {
        body += escapeRegExp(part.literal);
        continue;
      }
      placeholderNumber += 1;
      body += placeholderNumber === placeholders.length ? '([\\\\s\\\\S]+)' : '([\\\\s\\\\S]+?)';
    }
    return { regex: new RegExp('^' + body + '$'), target: String(pattern.target) };
  }

  function translate(source, values) {
    var key = String(source);
    var dict = compileFor(locale);
    var mapped = dict.strings[key];
    if (mapped === undefined) mapped = dict.patternMap[key];
    if (mapped === undefined) {
      // Composite sentences assembled from translated pieces (for example
      // "Waiting 16 · A-T3a") still need to reach their pattern.
      for (var index = 0; index < dict.matchers.length; index += 1) {
        var matcher = dict.matchers[index];
        var match = matcher.regex.exec(key);
        if (!match) continue;
        var captures = [];
        for (var capture = 1; capture < match.length; capture += 1) captures.push(match[capture]);
        return interpolate(matcher.target, captures);
      }
      mapped = key;
    }
    return interpolate(mapped, values);
  }

  function localizeText(value) {
    var source = String(value == null ? '' : value);
    var leading = (source.match(/^\\s*/) || [''])[0];
    var trailing = (source.match(/\\s*$/) || [''])[0];
    var core = source.slice(leading.length, source.length - trailing.length);
    if (!core) return source;
    var dict = compileFor(locale);
    var mapped = dict.strings[core];
    if (mapped !== undefined) return leading + interpolate(mapped) + trailing;
    for (var index = 0; index < dict.matchers.length; index += 1) {
      var matcher = dict.matchers[index];
      var match = matcher.regex.exec(core);
      if (!match) continue;
      var values = [];
      for (var capture = 1; capture < match.length; capture += 1) values.push(match[capture]);
      return leading + interpolate(matcher.target, values) + trailing;
    }
    return source;
  }

  var textSources = typeof WeakMap === 'function' ? new WeakMap() : null;
  var attributeSources = typeof WeakMap === 'function' ? new WeakMap() : null;
  var ATTRIBUTES = ['title', 'aria-label', 'placeholder', 'alt'];

  function attributeOf(element, name) {
    try {
      return element.getAttribute(name);
    } catch (error) {
      return null;
    }
  }

  function skipped(element) {
    var current = element;
    while (current && current.nodeType === 1) {
      try {
        if (current.hasAttribute && current.hasAttribute('data-i18n-skip')) return true;
        if (current.isContentEditable) return true;
      } catch (error) { /* detached or exotic node */ }
      var tag = current.tagName ? String(current.tagName).toLowerCase() : '';
      if (tag === 'script' || tag === 'style' || tag === 'textarea' || tag === 'code' || tag === 'pre') return true;
      current = current.parentElement;
    }
    return false;
  }

  function localizeAttributes(root) {
    if (!root || !root.querySelectorAll) return 0;
    var changed = 0;
    var elements = root.querySelectorAll('[title], [aria-label], [placeholder], [alt]');
    for (var index = 0; index < elements.length; index += 1) {
      var element = elements[index];
      if (skipped(element)) continue;
      var stored = attributeSources && attributeSources.get(element);
      for (var position = 0; position < ATTRIBUTES.length; position += 1) {
        var name = ATTRIBUTES[position];
        var current = attributeOf(element, name);
        if (current == null) continue;
        var previous = stored && stored[name];
        var source = previous && current === previous.output ? previous.source : current;
        var translated = localizeText(source);
        if (translated !== current) {
          element.setAttribute(name, translated);
          changed += 1;
        }
        if (attributeSources) {
          if (!stored) {
            stored = {};
            attributeSources.set(element, stored);
          }
          stored[name] = { source: source, output: translated };
        }
      }
    }
    return changed;
  }

  function localizeTextNodes(root) {
    if (!root || !root.querySelectorAll) return 0;
    var doc = root.ownerDocument || root;
    if (!doc || typeof doc.createTreeWalker !== 'function') return 0;
    var walker = doc.createTreeWalker(root, 4, null, false);
    var changed = 0;
    var node = walker.nextNode();
    while (node) {
      var parent = node.parentElement;
      if (parent && !skipped(parent)) {
        var current = node.nodeValue;
        if (current) {
          var previous = textSources && textSources.get(node);
          var source = previous && current === previous.output ? previous.source : current;
          var translated = localizeText(source);
          if (translated !== current) {
            node.nodeValue = translated;
            changed += 1;
          }
          if (textSources) textSources.set(node, { source: source, output: translated });
        }
      }
      node = walker.nextNode();
    }
    return changed;
  }

  function localize(root) {
    var scope = root || global.document;
    if (!scope) return 0;
    var changed = localizeAttributes(scope);
    changed += localizeTextNodes(scope);
    return changed;
  }

  function setLocale(value) {
    var next = normalizeLocale(value);
    if (!next || LOCALES.indexOf(next) < 0) return false;
    locale = next;
    timeZone = resolveTimeZone();
    if (typeof api !== 'undefined') {
      api.locale = next;
      api.timeZone = timeZone;
    }
    if (global.document && global.document.documentElement && global.document.documentElement.setAttribute) {
      try {
        global.document.documentElement.setAttribute('lang', next);
      } catch (error) { /* optional */ }
    }
    try {
      if (global.localStorage) global.localStorage.setItem(LOCALE_STORAGE_KEY, next);
    } catch (error) { /* storage is optional */ }
    localize(global.document);
    try {
      if (global.document && typeof global.document.dispatchEvent === 'function' && typeof CustomEvent === 'function') {
        global.document.dispatchEvent(new CustomEvent('agent-teams:locale-changed', { detail: { locale: next } }));
      }
    } catch (error) { /* optional */ }
    return true;
  }

  function formatTime(value, options) {
    var date = value instanceof Date ? value : new Date(value == null ? Date.now() : value);
    if (Number.isNaN(date.getTime())) return '—';
    var settings = { hour12: false };
    if (options && typeof options === 'object') {
      for (var key in options) settings[key] = options[key];
    }
    settings.timeZone = resolveTimeZone();
    try {
      return date.toLocaleTimeString(locale, settings);
    } catch (error) {
      try {
        delete settings.timeZone;
        return date.toLocaleTimeString(locale, settings);
      } catch (fallback) {
        return date.toISOString();
      }
    }
  }

  function boot() {
    if (!global.document) return;
    if (global.document.documentElement && global.document.documentElement.setAttribute) {
      try {
        global.document.documentElement.setAttribute('lang', locale);
      } catch (error) { /* optional */ }
    }
    localize(global.document);
  }

  var api = {
    locale: locale,
    t: translate,
    localize: localize,
    localizeText: localizeText,
    setLocale: setLocale,
    formatTime: formatTime,
    getTimeZone: resolveTimeZone,
    timeZone: timeZone,
    supportedLocales: LOCALES.slice(),
    dataLocales: Object.keys(DATA),
  };

  global.AGT_I18N = api;
  if (global.window && global.window !== global) global.window.AGT_I18N = api;

  try {
    if (global.document) {
      if (global.document.readyState === 'loading' && typeof global.document.addEventListener === 'function') {
        global.document.addEventListener('DOMContentLoaded', boot, { once: true });
      } else {
        boot();
      }
    }
  } catch (error) { /* localization is best-effort in exotic hosts */ }
})(typeof window !== 'undefined' ? window : globalThis);
`;

function placeholderList(value) {
  return [...String(value).matchAll(/\{(\d+)\}/g)].map((match) => Number(match[1])).sort((a, b) => a - b);
}

function samePlaceholders(left, right) {
  const a = placeholderList(left);
  const b = placeholderList(right);
  return a.length === b.length && a.every((value, index) => value === b[index]);
}

function readLocale(root, name) {
  const file = join(root, 'locales', `${name}.json`);
  const parsed = JSON.parse(readFileSync(file, 'utf8'));
  if (parsed.locale !== name) throw new Error(`${file}: locale must be ${name}`);
  if (typeof parsed.name !== 'string' || !parsed.name.trim()) throw new Error(`${file}: name is required`);
  if (!parsed.strings || typeof parsed.strings !== 'object' || Array.isArray(parsed.strings)) {
    throw new Error(`${file}: strings must be an object`);
  }
  if (!Array.isArray(parsed.patterns)) throw new Error(`${file}: patterns must be an array`);
  for (const [key, value] of Object.entries(parsed.strings)) {
    if (typeof value !== 'string' || !value.trim()) throw new Error(`${file}: empty translation for ${key}`);
    if (!samePlaceholders(key, value)) throw new Error(`${file}: placeholder mismatch for ${key}`);
  }
  const seen = new Set();
  for (const pattern of parsed.patterns) {
    if (!pattern || typeof pattern.source !== 'string' || typeof pattern.target !== 'string') {
      throw new Error(`${file}: each pattern needs source and target`);
    }
    if (!pattern.source.trim() || !pattern.target.trim()) throw new Error(`${file}: empty pattern`);
    if (seen.has(pattern.source)) throw new Error(`${file}: duplicate pattern ${pattern.source}`);
    seen.add(pattern.source);
    if (!samePlaceholders(pattern.source, pattern.target)) {
      throw new Error(`${file}: placeholder mismatch for pattern ${pattern.source}`);
    }
  }
  return { locale: parsed.locale, name: parsed.name, strings: parsed.strings, patterns: parsed.patterns };
}

export function loadLocales(root = resolve('.')) {
  const result = {};
  for (const name of LOCALES) result[name] = readLocale(root, name);
  const source = result['zh-CN'];
  const keys = Object.keys(source.strings);
  const keySet = new Set(keys);
  const patternSources = source.patterns.map((pattern) => pattern.source);
  for (const name of LOCALES) {
    if (name === 'zh-CN') continue;
    const locale = result[name];
    const ownKeys = Object.keys(locale.strings);
    if (ownKeys.length !== keys.length) {
      throw new Error(`${name}: ${ownKeys.length} strings vs zh-CN ${keys.length}`);
    }
    for (const key of ownKeys) {
      if (!keySet.has(key)) throw new Error(`${name}: key not in zh-CN: ${key}`);
    }
    const ownSources = locale.patterns.map((pattern) => pattern.source);
    if (ownSources.length !== patternSources.length) {
      throw new Error(`${name}: ${ownSources.length} patterns vs zh-CN ${patternSources.length}`);
    }
    for (const patternSource of ownSources) {
      if (!patternSources.includes(patternSource)) throw new Error(`${name}: pattern not in zh-CN: ${patternSource}`);
    }
  }
  return result;
}

export function buildI18n(root = resolve('.')) {
  const data = loadLocales(root);
  const serialized = JSON.stringify(data).replace(/<\//g, '<\\/');
  const runtime = RUNTIME
    .replace('__I18N_DATA__', serialized)
    .replace('__I18N_LOCALES__', JSON.stringify(LOCALES))
    .replace('__I18N_DEFAULT__', JSON.stringify(DEFAULT_LOCALE));
  writeFileSync(join(root, 'assets', 'team-view-i18n.js'), runtime, 'utf8');

  // The live view is inlined by the daemon together with its fixed asset list.
  // Keep the runtime inside that asset so /ui still serves the same script count
  // while remaining fully offline.
  const livePath = join(root, 'assets', 'team-view-live.js');
  const live = readFileSync(livePath, 'utf8');
  const jsStart = live.indexOf(JS_START);
  const jsEnd = live.indexOf(JS_END);
  if (jsStart < 0 || jsEnd < 0 || jsEnd < jsStart) {
    throw new Error(`assets/team-view-live.js needs the generated i18n markers ${JS_START} ... ${JS_END}`);
  }
  const jsBlock = `${JS_START}\n${runtime}\n${JS_END}`;
  writeFileSync(livePath, live.slice(0, jsStart) + jsBlock + live.slice(jsEnd + JS_END.length), 'utf8');

  const htmlPath = join(root, 'assets', 'team-view.html');
  const html = readFileSync(htmlPath, 'utf8');
  const start = html.indexOf(HTML_START);
  const end = html.indexOf(HTML_END);
  if (start < 0 || end < 0 || end < start) {
    throw new Error(`assets/team-view.html needs the generated i18n markers ${HTML_START} ... ${HTML_END}`);
  }
  const block = `${HTML_START}\n${HTML_END}`;
  const next = html.slice(0, start) + block + html.slice(end + HTML_END.length);
  writeFileSync(htmlPath, next, 'utf8');

  const counts = LOCALES.map((name) => `${name}:${Object.keys(data[name].strings).length}s/${data[name].patterns.length}p`).join(' ');
  console.log(`BUILT assets/team-view-i18n.js (${counts})`);
  return { data, runtime };
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) buildI18n();
